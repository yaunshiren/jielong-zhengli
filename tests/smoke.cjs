const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
assert.match(html, /rel="canonical"/);
assert.match(html, /href="guide\.html"/);
assert(fs.existsSync('guide.html'));
assert(fs.existsSync('sitemap.xml'));
const scripts = [...html.matchAll(/<script(?:\s+[^>]*)?>([\s\S]*?)<\/script>/g)];
const logic = scripts.find(x => x[1].includes('接龙整理台 v0.2.0'));
assert(logic, 'core script missing');
const sandbox = { module: { exports: {} } };
vm.runInNewContext(logic[1], sandbox, { timeout: 2000 });
const core = sandbox.module.exports;
const {people,skipped} = core.parse('标题\n1 张三+1 已付款\n2：李四 取消报名\n3. 王五 共3人\n4、王五 待确认\n');
assert.equal(people.length,4);
assert.equal(skipped.length,1);
assert.equal(core.summarize(people).rows,3);
assert.equal(core.summarize(people).attendees,6);
assert.equal(core.summarize(people).warnings,2);
assert(!core.asCsv(people).includes('李四'));
const csv = core.asCsv(core.parse('1. =HYPERLINK("https://example.com")').people);
assert(csv.includes("'=HYPERLINK"), 'CSV formula injection');
console.log('PASS: landing, guide, parser, counts, duplicates, CSV protection');
